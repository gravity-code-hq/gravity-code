import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const directory = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const lucideDirectory = path.dirname(require.resolve("lucide-react-native/package.json"));
const license = await fs.readFile(path.join(lucideDirectory, "LICENSE"), "utf8");
const result = await esbuild.build({
  stdin: {
    contents:
      'import * as icons from "lucide-react-native/dist/esm/icons/index.js"; import { installVisualizationRuntime } from "./runtime"; globalThis.__gravityInstallVisualization = labels => installVisualizationRuntime(icons, labels);',
    resolveDir: directory,
  },
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["ios15", "chrome100"],
  minify: true,
  banner: { js: `/*! Lucide icon data\n${license}\n*/` },
  plugins: [
    {
      name: "lucide-svg-nodes",
      setup(build) {
        // Reuse the installed icon data without React or the native SVG renderer.
        build.onLoad({ filter: /lucide-react-native\/dist\/esm\/createLucideIcon\.js$/ }, () => ({
          contents: "export default function createLucideIcon(name, nodes) { return nodes; }",
          loader: "js",
        }));
      },
    },
  ],
});
const javascript = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const css = await fs.readFile(path.join(directory, "runtime.css"), "utf8");
await fs.writeFile(
  path.join(directory, "runtime.gen.ts"),
  `// Generated by build-runtime.mjs. Includes Lucide icon data (ISC license).\n// Do not edit by hand.\nexport const visualizationRuntime = ${JSON.stringify(javascript)};\nexport const visualizationStyles = ${JSON.stringify(css)};\n`,
);
