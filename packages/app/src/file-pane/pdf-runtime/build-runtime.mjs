import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../../../../..");
const output = path.join(__dirname, "html.gen.ts");

const [script, styles] = await Promise.all([
  esbuild.build({
    entryPoints: [path.join(__dirname, "entry.ts")],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: ["chrome120", "safari17"],
    minify: true,
    // pdf.js only reads import.meta.url to locate its wasm decoders and the Node
    // canvas; the runtime disables wasm and never runs under Node.
    define: { "import.meta.url": '""' },
    legalComments: "none",
    logLevel: "warning",
  }),
  esbuild.build({
    entryPoints: [path.join(__dirname, "runtime.css")],
    bundle: true,
    write: false,
    minify: true,
    loader: { ".svg": "dataurl", ".gif": "dataurl", ".png": "dataurl" },
    logLevel: "warning",
  }),
]);

const rawJs = script.outputFiles[0]?.text;
const css = styles.outputFiles[0]?.text;
if (!rawJs || !css) {
  throw new Error("PDF runtime bundle produced no output");
}
// An embedded closing-script sequence would terminate the inline <script>.
const js = rawJs.replace(/<\/script/gi, "<\\/script");

const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta
      http-equiv="Content-Security-Policy"
      content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'none'; img-src data: blob:; font-src data:; media-src 'none'; object-src 'none'; frame-src 'none'; base-uri 'none'; form-action 'none'"
    />
    <style>${css}</style>
  </head>
  <body>
    <div id="viewerContainer"><div id="viewer" class="pdfViewer"></div></div>
    <script>${js}</script>
  </body>
</html>`;

const contents = `// Generated by packages/app/src/file-pane/pdf-runtime/build-runtime.mjs.
// Includes pdf.js (Apache-2.0). Do not edit by hand.

export const pdfRuntimeHtml = ${JSON.stringify(html)};
`;

await fs.writeFile(output, contents);
console.log(`Wrote ${path.relative(repoRoot, output)} (${html.length} bytes)`);
